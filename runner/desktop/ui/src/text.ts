export const textFor = (lang: string | undefined): Text => (/^zh/i.test(lang ?? '') ? ZH : EN)

/** "3 分钟前" / "3m": whole minutes, hours past the hour, days past the day. */
export function since(at: string, t: Text, form: 'ago' | 'lasted', now = Date.now()): string {
  const minutes = Math.max(0, Math.floor((now - Date.parse(at)) / 60_000))
  if (form === 'ago' && minutes < 1) return t.now
  const [n, unit] = minutes < 60 ? [Math.max(1, minutes), 'm' as const] : minutes < 1440 ? [Math.floor(minutes / 60), 'h' as const] : [Math.floor(minutes / 1440), 'd' as const]
  return t[form](n, unit)
}
