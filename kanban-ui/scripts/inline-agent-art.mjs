// Writes lib/agent-art.ts: every avatar in public/agent-art/ as a data URL, so a list of
// characters draws with its text instead of after a round trip to the server.
// `character-design/draw.mjs` runs it; run it by hand after adding a PNG yourself.

import fs from "node:fs";
import path from "node:path";

const root = path.dirname(new URL(".", import.meta.url).pathname);
const dir = path.join(root, "public", "agent-art");
const lines = fs
  .readdirSync(dir)
  .filter((f) => f.endsWith(".png"))
  .sort()
  .map((f) => `  ${JSON.stringify(f.slice(0, -4))}: "data:image/png;base64,${fs.readFileSync(path.join(dir, f)).toString("base64")}",`);
fs.writeFileSync(
  path.join(root, "lib", "agent-art.ts"),
  `// Generated by scripts/inline-agent-art.mjs from public/agent-art/ — do not edit.\nexport const AGENT_ART: Record<string, string> = {\n${lines.join("\n")}\n};\n`,
);
