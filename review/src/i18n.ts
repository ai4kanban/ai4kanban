export type Lang = "zh" | "en";

const LANG_KEY = "wildcrane.lang";

const picked = (): string | null => {
  try {
    return globalThis.localStorage?.getItem(LANG_KEY) ?? null;
  } catch {
    return null;
  }
};

export const LANG: Lang = (() => {
  const p = picked();
  if (p === "zh" || p === "en") return p;
  return /^zh\b/i.test(globalThis.navigator?.language ?? "") ? "zh" : "en";
})();

/** Keeps the pick in this browser and reloads, since every word was chosen at load. */
export const pickLang = (lang: Lang) => {
  localStorage.setItem(LANG_KEY, lang);
  location.reload();
};

